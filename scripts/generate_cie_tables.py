"""Retain PBRT's complete CIE 1931 and D65 tables, without resampling.

Usage: python scripts/generate_cie_tables.py path/to/pbrt/util/spectrum.cpp
"""

from pathlib import Path
import hashlib
import re
import sys


def main():
    source = Path(sys.argv[1]).read_bytes()
    text = source.decode()
    arrays = {}
    for name in ("CIE_X", "CIE_Y", "CIE_Z", "CIE_lambda", "CIE_Illum_D6500"):
        match = re.search(rf"const Float {name}\[[^]]*\] = \{{(.*?)\}};", text, re.S)
        if match is None:
            raise ValueError(f"missing {name}")
        body = re.sub(r"//[^\n]*", "", match[1])
        arrays[name] = re.findall(r"[-+]?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?", body)
    assert [float(x) for x in arrays["CIE_lambda"]] == list(range(360, 831))
    assert all(len(arrays[name]) == 471 for name in ("CIE_X", "CIE_Y", "CIE_Z"))
    assert len(arrays["CIE_Illum_D6500"]) % 2 == 0
    assert [float(x) for x in arrays["CIE_Illum_D6500"][::2]] == list(range(300, 831, 5))
    out = [
        '# SPDX-License-Identifier: Apache-2.0\n',
        '# Tables from pbrt, Copyright (c) 1998-2020 Matt Pharr, Wenzel Jakob,\n',
        '# and Greg Humphreys. See bajo/parser/pbrt/LICENSE-pbrt.txt.\n',
        '# Source: https://github.com/mmp/pbrt-v4/blob/master/src/pbrt/util/spectrum.cpp\n',
        f'# Source SHA-256: {hashlib.sha256(source).hexdigest()}\n',
        '# Generated by scripts/generate_cie_tables.py; original values are unchanged.\n\n',
        'from bajo.core.vec import Vec3\n\n',
        'comptime Color = Vec3[.float32, .WORLD]\n\n',
        '# 360 through 830 nm, inclusive, at every original 1 nm sample.\n',
        'comptime CIE_XYZ: Array[Color, 471] = [\n',
    ]
    for xyz in zip(arrays["CIE_X"], arrays["CIE_Y"], arrays["CIE_Z"]):
        out.append('    Color(' + ', '.join(xyz) + '),\n')
    out.extend([']\n\n', f'comptime D65: Array[Float32, {len(arrays["CIE_Illum_D6500"])}] = [\n'])
    for i in range(0, len(arrays["CIE_Illum_D6500"]), 2):
        out.append('    ' + ', '.join(arrays["CIE_Illum_D6500"][i:i+2]) + ',\n')
    out.append(']\n')
    destination = Path(__file__).resolve().parents[1] / 'bajo/core/cie_data.mojo'
    destination.write_text(''.join(out))


if __name__ == '__main__':
    main()
