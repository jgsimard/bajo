"""Copy PBRT's original optical tables into Mojo without fitting RGB constants.

Usage: python scripts/generate_optical_spectra.py path/to/pbrt/util/spectrum.cpp
Source: https://github.com/mmp/pbrt-v4/blob/master/src/pbrt/util/spectrum.cpp
"""

from pathlib import Path
import hashlib
import re
import sys


def main():
    source = Path(sys.argv[1]).read_bytes()
    text = source.decode()
    metals = ("Al", "Au", "Cu", "CuZn")
    output = [
        '# SPDX-License-Identifier: Apache-2.0\n',
        '# Tables from pbrt, Copyright (c) 1998-2020 Matt Pharr, Wenzel Jakob,\n',
        '# and Greg Humphreys. Licensed under the Apache License, Version 2.0.\n',
        '# https://www.apache.org/licenses/LICENSE-2.0\n',
        '# Original source: https://github.com/mmp/pbrt-v4/blob/master/src/pbrt/util/spectrum.cpp\n',
        f'# Source SHA-256: {hashlib.sha256(source).hexdigest()}\n',
        '# Generated by scripts/generate_optical_spectra.py; values are unchanged.\n\n',
        'from bajo.core.spectrum import PiecewiseLinearSpectrum\n\n\n',
        'def named_optical_spectrum(name: ImmStringSpan) raises -> PiecewiseLinearSpectrum:\n',
        '    """Original wavelength tables, including the brass used by Bistro."""\n',
        '    match name:\n',
    ]
    for metal in metals:
        for component in ("eta", "k"):
            match = re.search(
                rf"const Float {metal}_{component}\[\] = \{{(.*?)\}};",
                text,
                re.S,
            )
            if match is None:
                raise ValueError(f"missing {metal}_{component}")
            values = re.findall(r"[-+]?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?", match[1])
            if len(values) < 4 or len(values) % 2:
                raise ValueError(f"invalid {metal}_{component}")
            output.append(f'        case "metal-{metal}-{component}":\n')
            output.append('            return PiecewiseLinearSpectrum([\n')
            for index in range(0, len(values), 8):
                output.append('                ' + ', '.join(values[index:index + 8]) + ',\n')
            output.append('            ])\n')
    output.extend([
        '        case _:\n',
        '            raise Error("unsupported PBRT optical spectrum: " + String(name))\n',
    ])
    destination = Path(__file__).resolve().parents[1] / 'bajo/parser/pbrt/optical_data.mojo'
    destination.write_text(''.join(output))


if __name__ == "__main__":
    main()
